-- 0012_compliance_cases: 历史合规处罚案例库 + 候选变体相似度比对.
--
-- 现有合规三道门:
--   1. 关键词扫描(命中 A/B 级直接拦)
--   2. LLM 语义审查(豆包模型给意见)
--   3. 人工复核
--
-- 三道门补不齐的盲区:**真实处罚案例**.
--   - 2024 昆明某口腔诊所因 "手术时间最短" 被罚 5 万
--   - 2023 北京某医院因 "100% 零失误" 被处广告法 5W
--   - ... 这些都是公开判例,候选变体很可能犯同样的错
--
-- 第四道门 = 把这些真实案例的违规要素加进比对池,候选文案命中
-- 类似要素 → 弹"跟 XX 案例(罚款 XX 万)相似" 警告,要求人工二审.
--
-- 案例数据来源(公开):
--   - 国家市场监督管理总局 行政处罚信息公示
--   - 卫健委 医疗广告违规公告
--   - 各地市监局公示
--   - 地方医疗机构信用档案
--
-- 数据结构:
--   - title: 简短标题 (违规机构 + 时间 + 主因)
--   - violation_patterns: 关键短语列表(候选变体里出现这些就触发匹配)
--   - violation_category: 大类(夸大疗效/绝对化/患者画像 等)
--   - jurisdiction: 处罚地区
--   - fine_yuan: 罚款金额
--   - case_url: 公示链接
--   - notes: 上下文 / 教训
--
-- match 算法(应用层):
--   命中 ≥ 50% 的 patterns → suspected_match
--   命中 < 50% → 不报警
-- 用 jaccard(交集 / 并集)平衡精度和召回.
--
-- 跨租户共享(不属于 tenant) — 案例是公开信息,所有租户都能学习,这跟
-- verified_citations(每租户自维)正好相反.

CREATE TABLE compliance_cases (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  -- 案例标题
  title TEXT NOT NULL,
  -- 违规要素短语 — 候选文案里出现就算命中
  violation_patterns TEXT[] NOT NULL,
  -- 大类
  violation_category TEXT NOT NULL,
  -- 处罚地点(省/市)
  jurisdiction TEXT,
  -- 罚款金额(元)
  fine_yuan INTEGER,
  -- 处罚日期(精确到月即可)
  punished_at DATE,
  -- 案例公示 URL
  case_url TEXT,
  -- 经验教训
  notes TEXT,
  -- 案例还是否生效(法规过期就软关)
  active BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  deleted_at TIMESTAMPTZ
);

CREATE INDEX compliance_cases_active_idx
  ON compliance_cases (active) WHERE deleted_at IS NULL;
CREATE INDEX compliance_cases_category_idx
  ON compliance_cases (violation_category) WHERE deleted_at IS NULL;

COMMENT ON TABLE compliance_cases IS
  '公开监管处罚案例库,跨租户共享.候选文案与案例 violation_patterns 交集 ≥ 50% 触发警告.';

-- variant 侧:存这次扫描命中的 case 列表
ALTER TABLE content_variants
  ADD COLUMN IF NOT EXISTS case_match JSONB;

COMMENT ON COLUMN content_variants.case_match IS
  '{ scanned_at, matches: [{ case_id, similarity, matched_patterns }] }.候选文案与历史案例的相似度.';

